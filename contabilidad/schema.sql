-- Esquema H2. Se ejecuta en cada arranque (idempotente).
CREATE TABLE IF NOT EXISTS cuentas (
  codigo VARCHAR(20) PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  tipo   VARCHAR(10)  NOT NULL CHECK (tipo IN ('ACTIVO','PASIVO','PATRIMONIO','INGRESO','GASTO'))
);

CREATE TABLE IF NOT EXISTS asientos (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY (NO CACHE) PRIMARY KEY, -- sin saltos de numeración al reiniciar
  fecha       DATE NOT NULL,
  descripcion VARCHAR(200) NOT NULL
);

CREATE TABLE IF NOT EXISTS movimientos (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asiento_id    BIGINT NOT NULL REFERENCES asientos(id),
  cuenta_codigo VARCHAR(20) NOT NULL REFERENCES cuentas(codigo),
  debe          DECIMAL(15,2) NOT NULL DEFAULT 0,
  haber         DECIMAL(15,2) NOT NULL DEFAULT 0,
  CHECK ((debe > 0 AND haber = 0) OR (haber > 0 AND debe = 0))
);

